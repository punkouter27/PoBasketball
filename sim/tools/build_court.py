"""Task A4: generate sim/assets/court.xml (floor, two hoops, fence, ball).

All dimensions are FIBA regulation in metres, MuJoCo frame (Z-up, right-handed).
Court centre is the origin; the long axis is X (+X toward the "east" hoop).

Usage: uv run python tools/build_court.py [--ball-solref T D]
"""
import argparse
import math
import pathlib

ASSETS = pathlib.Path(__file__).resolve().parents[1] / "assets"

# --- Court -------------------------------------------------------------------
COURT_L, COURT_W = 28.0, 15.0
FENCE_MARGIN = 2.0          # fence sits this far outside the lines
FENCE_H = 3.0
FENCE_T = 0.05

# --- Hoop --------------------------------------------------------------------
RIM_H = 3.05
RIM_R = 0.2286              # inner radius (45.72 cm diameter)
RIM_TUBE_R = 0.009          # steel tube radius
RIM_SEGMENTS = 12
RIM_FROM_BASELINE = 1.575   # rim centre to baseline
BOARD_W, BOARD_H, BOARD_T = 1.80, 1.05, 0.03
BOARD_BOTTOM = 2.90
BOARD_FROM_BASELINE = 1.20  # backboard face to baseline
POLE_R = 0.06
POLE_FROM_BASELINE = 2.20   # outdoor goose-neck pole behind the board
POLE_H = 3.95

# --- Ball --------------------------------------------------------------------
BALL_R = 0.1205
BALL_MASS = 0.62


def rim_segments(cx: float, cy: float, cz: float) -> str:
    out = []
    for i in range(RIM_SEGMENTS):
        a0 = 2 * math.pi * i / RIM_SEGMENTS
        a1 = 2 * math.pi * (i + 1) / RIM_SEGMENTS
        x0, y0 = cx + RIM_R * math.cos(a0), cy + RIM_R * math.sin(a0)
        x1, y1 = cx + RIM_R * math.cos(a1), cy + RIM_R * math.sin(a1)
        out.append(
            f'      <geom name="rim_{"e" if cx > 0 else "w"}_{i:02d}" class="rim" type="capsule" '
            f'fromto="{x0:.4f} {y0:.4f} {cz:.4f} {x1:.4f} {y1:.4f} {cz:.4f}"/>'
        )
    return "\n".join(out)


def hoop(side: int) -> str:
    """side = +1 (east, +X) or -1 (west, -X)."""
    tag = "e" if side > 0 else "w"
    base_x = side * COURT_L / 2
    rim_x = base_x - side * RIM_FROM_BASELINE
    board_x = base_x - side * BOARD_FROM_BASELINE
    pole_x = base_x + side * (POLE_FROM_BASELINE - 0.0)
    board_cz = BOARD_BOTTOM + BOARD_H / 2
    # Goose-neck arm from pole top to board top centre
    arm_z = BOARD_BOTTOM + BOARD_H - 0.10
    return f"""    <body name="hoop_{tag}">
      <geom name="pole_{tag}" class="steel" type="capsule" fromto="{pole_x:.3f} 0 0 {pole_x:.3f} 0 {POLE_H:.3f}" size="{POLE_R}"/>
      <geom name="arm_{tag}" class="steel" type="capsule" fromto="{pole_x:.3f} 0 {POLE_H:.3f} {board_x:.3f} 0 {arm_z:.3f}" size="0.035"/>
      <geom name="board_{tag}" class="board" type="box" pos="{board_x + side * BOARD_T / 2:.4f} 0 {board_cz:.3f}" size="{BOARD_T / 2:.3f} {BOARD_W / 2:.3f} {BOARD_H / 2:.3f}"/>
      <geom name="rim_bracket_{tag}" class="steel" type="box" pos="{(board_x + rim_x + side * RIM_R) / 2:.4f} 0 {RIM_H - 0.02:.3f}" size="{abs(board_x - (rim_x + side * RIM_R)) / 2:.4f} 0.05 0.015"/>
{rim_segments(rim_x, 0.0, RIM_H)}
      <site name="rim_center_{tag}" pos="{rim_x:.4f} 0 {RIM_H:.3f}" size="0.01" rgba="1 0 0 0.3"/>
      <site name="score_{tag}" pos="{rim_x:.4f} 0 {RIM_H - 0.10:.3f}" size="0.01" rgba="0 1 0 0.3"/>
    </body>"""


def fence() -> str:
    hx = COURT_L / 2 + FENCE_MARGIN
    hy = COURT_W / 2 + FENCE_MARGIN
    hz = FENCE_H / 2
    return f"""    <body name="fence">
      <geom name="fence_n" class="fence" type="box" pos="0 {hy:.2f} {hz}" size="{hx:.2f} {FENCE_T} {hz}"/>
      <geom name="fence_s" class="fence" type="box" pos="0 {-hy:.2f} {hz}" size="{hx:.2f} {FENCE_T} {hz}"/>
      <geom name="fence_e" class="fence" type="box" pos="{hx:.2f} 0 {hz}" size="{FENCE_T} {hy:.2f} {hz}"/>
      <geom name="fence_w" class="fence" type="box" pos="{-hx:.2f} 0 {hz}" size="{FENCE_T} {hy:.2f} {hz}"/>
    </body>"""


def build(ball_solref=(0.01, 0.10)) -> str:
    sr = f"{ball_solref[0]:.4f} {ball_solref[1]:.4f}"
    return f"""<!-- GENERATED by tools/build_court.py. Edit the script, not this file. -->
<mujoco model="streetball_court">
  <option timestep="0.002" integrator="implicitfast" solver="Newton" iterations="8" ls_iterations="10" cone="elliptic" gravity="0 0 -9.81"/>
  <default>
    <default class="court">
      <geom contype="1" conaffinity="1" condim="6" friction="0.9 0.01 0.002" solref="0.01 1" solimp="0.9 0.95 0.001"/>
    </default>
    <default class="steel">
      <geom contype="1" conaffinity="1" condim="3" friction="0.5 0.005 0.0001" rgba="0.15 0.15 0.17 1"/>
    </default>
    <default class="rim">
      <geom contype="1" conaffinity="1" condim="3" friction="0.5 0.005 0.0001" size="{RIM_TUBE_R}" rgba="0.85 0.35 0.1 1"/>
    </default>
    <default class="board">
      <geom contype="1" conaffinity="1" condim="3" friction="0.4 0.005 0.0001" rgba="0.9 0.9 0.92 0.6"/>
    </default>
    <default class="fence">
      <geom contype="1" conaffinity="1" condim="3" friction="0.5 0.005 0.0001" rgba="0.4 0.4 0.42 0.35"/>
    </default>
    <default class="ball">
      <geom contype="1" conaffinity="1" condim="6" friction="0.6 0.02 0.005" priority="1"
            solref="{sr}" solimp="0.95 0.99 0.001" rgba="0.85 0.45 0.15 1"/>
    </default>
  </default>

  <asset>
    <texture name="asphalt" type="2d" builtin="checker" rgb1="0.22 0.22 0.23" rgb2="0.24 0.24 0.25" width="512" height="512"/>
    <material name="asphalt" texture="asphalt" texrepeat="28 15" reflectance="0.05"/>
  </asset>

  <worldbody>
    <light name="sun" directional="true" pos="0 0 30" dir="-0.3 -0.5 -1" diffuse="0.9 0.9 0.85" castshadow="true"/>
    <geom name="floor" class="court" type="plane" size="{COURT_L / 2 + FENCE_MARGIN:.2f} {COURT_W / 2 + FENCE_MARGIN:.2f} 0.1" material="asphalt"/>

{hoop(+1)}
{hoop(-1)}
{fence()}

    <body name="ball" pos="1.0 -0.6 {BALL_R:.4f}">
      <freejoint name="ball"/>
      <geom name="ball" class="ball" type="sphere" size="{BALL_R}" mass="{BALL_MASS}"/>
      <site name="ball_center" size="0.005"/>
    </body>
  </worldbody>

  <contact>
    <!-- Ball bounce is tuned by tools/tune_ball.py against the FIBA drop test. -->
    <pair name="ball_floor" geom1="ball" geom2="floor" condim="6" friction="0.6 0.6 0.02 0.005 0.005" solref="{sr}" solimp="0.95 0.99 0.001"/>
  </contact>

  <sensor>
    <framepos name="ball_pos" objtype="site" objname="ball_center"/>
    <framelinvel name="ball_vel" objtype="site" objname="ball_center"/>
  </sensor>
</mujoco>
"""


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--ball-solref", type=float, nargs=2, default=(0.01, 0.10))
    args = ap.parse_args()
    ASSETS.mkdir(parents=True, exist_ok=True)
    out = ASSETS / "court.xml"
    out.write_text(build(tuple(args.ball_solref)), encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
